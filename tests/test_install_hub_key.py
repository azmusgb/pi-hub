"""The hash install.sh prints must equal sha256 of the key as the hub sends it (stripped)."""
import hashlib, pathlib, subprocess, textwrap

SRC = (pathlib.Path(__file__).parent.parent / "deploy" / "install.sh").read_text()
SNIPPET = SRC.split("# hub-key-begin\n")[1].split("# hub-key-end")[0]


def run(tmp_path, existing=None):
    key = tmp_path / "key"
    if existing is not None:
        key.write_bytes(existing)
    body = SNIPPET.replace("/etc/pi-hub/secrets/localai_hub_key", str(key)).replace("sudo ", "")
    body = body.replace("chown root:pi-hub " + str(key) + " && ", "")
    r = subprocess.run(["bash", "-c", body], capture_output=True, text=True)
    return r, key


def test_printed_hash_matches_stripped_key(tmp_path):
    r, key = run(tmp_path)
    assert r.returncode == 0, r.stderr
    raw = key.read_bytes()
    assert not raw.endswith(b"\n")
    want = hashlib.sha256(raw.decode().strip().encode()).hexdigest()
    assert r.stdout.strip() == f"LOCALAI_HUB_KEY_SHA256={want}"


def test_existing_key_with_newline_hashes_stripped(tmp_path):
    r, _ = run(tmp_path, b"abc\n")
    assert r.stdout.strip() == "LOCALAI_HUB_KEY_SHA256=" + hashlib.sha256(b"abc").hexdigest()


def test_empty_key_is_refused(tmp_path):
    r, _ = run(tmp_path, b"\n")
    # an empty file is regenerated by the script ("test -s" fails only for size 0); a newline-only file must error
    assert r.returncode != 0 and "LOCALAI_HUB_KEY_SHA256" not in r.stdout
